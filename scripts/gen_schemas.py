#!/usr/bin/env python3
"""Generate PyArrow schemas and Pydantic models from schemas/schemas.yaml.

Usage:
    python scripts/gen_schemas.py            # (re)generate files in generated/
    python scripts/gen_schemas.py --check    # exit 1 if generated files are stale (for CI)

Outputs (deterministic, no timestamps, so diffs and --check are stable):
    generated/pyarrow_schemas.py   SCHEMAS, PRIMARY_KEYS, KAFKA, SCHEMA_VERSION
    generated/models.py            one Pydantic v2 model per table / message
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SPEC = ROOT / "schemas" / "schemas.yaml"
DEFAULT_OUT = ROOT / "generated"

# YAML type -> (PyArrow expression, Python annotation)
SCALAR_TYPES: dict[str, tuple[str, str]] = {
    "string": ("pa.string()", "str"),
    "int8": ("pa.int8()", "int"),
    "int16": ("pa.int16()", "int"),
    "int32": ("pa.int32()", "int"),
    "int64": ("pa.int64()", "int"),
    "float32": ("pa.float32()", "float"),
    "float64": ("pa.float64()", "float"),
    "bool": ("pa.bool_()", "bool"),
}
# Enums are stored as plain strings in Parquet (portable, no dictionary-encoding surprises)
# and validated as Literal[...] in Pydantic.
ENUM_ARROW = "pa.string()"

# Units that imply value constraints in Pydantic
UNIT_CONSTRAINTS = {"ratio_0_1": "ge=0, le=1"}

HEADER = '''# AUTO-GENERATED by scripts/gen_schemas.py from schemas/schemas.yaml. DO NOT EDIT.
# Schema version: {version}
'''


class SpecError(ValueError):
    pass


# --------------------------------------------------------------------------- spec


def load_spec(path: Path) -> dict:
    with path.open(encoding="utf-8") as f:
        spec = yaml.safe_load(f)
    validate_spec(spec)
    return spec


def _entities(spec: dict) -> dict[str, dict]:
    """Tables and messages share the same field format."""
    out: dict[str, dict] = {}
    for section in ("tables", "messages"):
        for name, body in (spec.get(section) or {}).items():
            if name in out:
                raise SpecError(f"duplicate entity name: {name}")
            out[name] = body
    return out


def validate_spec(spec: dict) -> None:
    if "schema_version" not in spec:
        raise SpecError("missing top-level 'schema_version'")
    entities = _entities(spec)
    if not entities:
        raise SpecError("no tables or messages defined")
    for name, body in entities.items():
        fields = body.get("fields")
        if not fields:
            raise SpecError(f"{name}: no fields defined")
        for fname, fdef in fields.items():
            where = f"{name}.{fname}"
            if not re.fullmatch(r"[a-z][a-z0-9_]*", fname):
                raise SpecError(f"{where}: field names must be snake_case")
            ftype = fdef.get("type")
            if ftype == "enum":
                values = fdef.get("values")
                if not values or not all(isinstance(v, str) for v in values):
                    raise SpecError(f"{where}: enum needs a non-empty list of string 'values'")
            elif ftype not in SCALAR_TYPES:
                raise SpecError(f"{where}: unknown type {ftype!r}")
            if "description" not in fdef:
                raise SpecError(f"{where}: missing 'description'")
        for key_field in body.get("primary_key", []):
            if key_field not in fields:
                raise SpecError(f"{name}: primary_key field {key_field!r} is not a defined field")
        kafka = body.get("kafka", {})
        kafka_fields = [kafka.get("event_time_field"), *kafka.get("idempotency_key", [])]
        for kf in kafka_fields:
            if kf and kf not in fields:
                raise SpecError(f"{name}: kafka field {kf!r} is not a defined field")


# ------------------------------------------------------------------- generators


def class_name(entity: str) -> str:
    return "".join(part.capitalize() for part in entity.split("_"))


def _py_str(s: str) -> str:
    """Safe Python string literal (repr handles quotes/escapes deterministically)."""
    return repr(s)


def gen_pyarrow(spec: dict) -> str:
    version = spec["schema_version"]
    lines = [HEADER.format(version=version), "import pyarrow as pa", ""]
    lines.append(f"SCHEMA_VERSION = {_py_str(str(version))}")
    lines.append("")
    lines.append("SCHEMAS: dict[str, pa.Schema] = {")
    entities = _entities(spec)
    for name, body in entities.items():
        lines.append(f"    {_py_str(name)}: pa.schema(")
        lines.append("        [")
        for fname, fdef in body["fields"].items():
            arrow = ENUM_ARROW if fdef["type"] == "enum" else SCALAR_TYPES[fdef["type"]][0]
            nullable = bool(fdef.get("nullable", False))
            meta = {"description": fdef["description"].strip()}
            if "unit" in fdef:
                meta["unit"] = str(fdef["unit"])
            if fdef["type"] == "enum":
                meta["enum_values"] = ",".join(fdef["values"])
            meta_src = "{" + ", ".join(f"{_py_str(k)}: {_py_str(v)}" for k, v in meta.items()) + "}"
            lines.append(
                f"            pa.field({_py_str(fname)}, {arrow}, nullable={nullable}, metadata={meta_src}),"
            )
        lines.append("        ],")
        lines.append(
            f"        metadata={{'schema_version': {_py_str(str(version))}, "
            f"'description': {_py_str(body.get('description', '').strip())}}},"
        )
        lines.append("    ),")
    lines.append("}")
    lines.append("")

    lines.append("PRIMARY_KEYS: dict[str, list[str]] = {")
    for name, body in entities.items():
        if "primary_key" in body:
            lines.append(f"    {_py_str(name)}: {list(body['primary_key'])!r},")
    lines.append("}")
    lines.append("")

    lines.append("KAFKA: dict[str, dict] = {")
    for name, body in entities.items():
        if "kafka" in body:
            lines.append(f"    {_py_str(name)}: {dict(body['kafka'])!r},")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _annotation(fdef: dict) -> str:
    if fdef["type"] == "enum":
        base = "Literal[" + ", ".join(_py_str(v) for v in fdef["values"]) + "]"
    else:
        base = SCALAR_TYPES[fdef["type"]][1]
    return f"{base} | None" if fdef.get("nullable", False) else base


def gen_models(spec: dict) -> str:
    version = spec["schema_version"]
    lines = [
        HEADER.format(version=version),
        "from __future__ import annotations",
        "",
        "from typing import Literal",
        "",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
        "",
    ]
    for name, body in _entities(spec).items():
        lines.append(f"class {class_name(name)}(BaseModel):")
        desc = body.get("description", "").strip().replace('"""', "'''")
        if desc:
            lines.append(f'    """{desc}"""')
            lines.append("")
        # extra=forbid catches schema drift; protected_namespaces=() allows a field named model_version
        lines.append("    model_config = ConfigDict(extra='forbid', protected_namespaces=())")
        lines.append("")
        for fname, fdef in body["fields"].items():
            annotation = _annotation(fdef)
            args = [f"description={_py_str(fdef['description'].strip())}"]
            unit = fdef.get("unit")
            if unit:
                constraint = UNIT_CONSTRAINTS.get(str(unit))
                if constraint:
                    args.insert(0, constraint)
                args.append(f"json_schema_extra={{'unit': {_py_str(str(unit))}}}")
            # Required-but-nullable: no default, so a missing key is an error, null is allowed.
            lines.append(f"    {fname}: {annotation} = Field({', '.join(args)})")
        lines.append("")
        lines.append("")
    lines.append("MODELS: dict[str, type[BaseModel]] = {")
    for name in _entities(spec):
        lines.append(f"    {_py_str(name)}: {class_name(name)},")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


# ------------------------------------------------------------------------- main


def render(spec: dict) -> dict[str, str]:
    return {
        "pyarrow_schemas.py": gen_pyarrow(spec),
        "models.py": gen_models(spec),
        "__init__.py": HEADER.format(version=spec["schema_version"]),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="fail if generated files differ from the spec")
    args = ap.parse_args(argv)

    try:
        spec = load_spec(args.spec)
    except SpecError as e:
        print(f"schema error: {e}", file=sys.stderr)
        return 2

    outputs = render(spec)
    if args.check:
        stale = [
            n for n, content in outputs.items()
            if not (args.out / n).exists() or (args.out / n).read_text(encoding="utf-8") != content
        ]
        if stale:
            print(f"stale generated files: {', '.join(stale)}. Run scripts/gen_schemas.py", file=sys.stderr)
            return 1
        print("generated files are up to date")
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        (args.out / name).write_text(content, encoding="utf-8")
        print(f"wrote {args.out / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
